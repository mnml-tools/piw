//! Window labels. Labels are the identity of a window across the app: a sticky window's label
//! is derived from its target, so the same item can never be opened twice.

use serde::{Deserialize, Serialize};
use ts_rs::TS;

pub const MAIN: &str = "main";
pub const CAPTURE: &str = "capture";
const STICKY_PREFIX: &str = "sticky";

/// The kind of item a sticky window displays.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(export, export_to = "bindings/")]
pub enum StickyKind {
    Note,
    Task,
    /// A "Tasks" tab of a document.
    TasksTab,
}

impl StickyKind {
    fn as_str(self) -> &'static str {
        match self {
            Self::Note => "note",
            Self::Task => "task",
            Self::TasksTab => "tasks_tab",
        }
    }

    fn parse(value: &str) -> Option<Self> {
        match value {
            "note" => Some(Self::Note),
            "task" => Some(Self::Task),
            "tasks_tab" => Some(Self::TasksTab),
            _ => None,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export, export_to = "bindings/")]
pub struct StickyTarget {
    pub kind: StickyKind,
    pub id: String,
}

impl StickyTarget {
    /// Window label for this target. Tauri labels accept `a-zA-Z0-9-/:_`; ids are UUIDs.
    pub fn label(&self) -> String {
        format!("{STICKY_PREFIX}:{}:{}", self.kind.as_str(), self.id)
    }

    pub fn from_label(label: &str) -> Option<Self> {
        let mut parts = label.splitn(3, ':');
        if parts.next()? != STICKY_PREFIX {
            return None;
        }
        let kind = StickyKind::parse(parts.next()?)?;
        let id = parts.next()?;
        is_valid_id(id).then(|| Self {
            kind,
            id: id.to_owned(),
        })
    }
}

/// Ids are generated by the app (UUIDs), but labels can also come from the UI, so only
/// characters that are valid in a Tauri label are accepted.
pub fn is_valid_id(id: &str) -> bool {
    !id.is_empty()
        && id.len() <= 64
        && id
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
}

pub fn is_sticky(label: &str) -> bool {
    StickyTarget::from_label(label).is_some()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn label_round_trips() {
        let target = StickyTarget {
            kind: StickyKind::TasksTab,
            id: "0190f1b2-7c3d-7a00-8000-000000000001".into(),
        };
        let label = target.label();
        assert_eq!(
            label,
            "sticky:tasks_tab:0190f1b2-7c3d-7a00-8000-000000000001"
        );
        assert_eq!(StickyTarget::from_label(&label), Some(target));
        assert!(is_sticky(&label));
    }

    #[test]
    fn rejects_foreign_or_malformed_labels() {
        assert_eq!(StickyTarget::from_label(MAIN), None);
        assert_eq!(StickyTarget::from_label("sticky:poem:abc"), None);
        assert_eq!(StickyTarget::from_label("sticky:note:"), None);
        assert_eq!(StickyTarget::from_label("sticky:note:a b"), None);
        assert!(!is_sticky("stickyish"));
    }
}
